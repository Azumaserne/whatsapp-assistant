/**
 * Resolve an explicit language token into 'zh' | 'en' | 'de' | null.
 * @param {string|null|undefined} raw
 * @returns {'zh'|'en'|'de'|null}
 */
function resolveExplicitLang(raw) {
    if (raw === null || raw === undefined) return null;
    const key = String(raw).trim().toLowerCase();
    return LANG_ALIASES[key] || null;
}

/**
 * Normalize a language value with fallback.
 * @param {string|null|undefined} raw
 * @param {'zh'|'en'|'de'} [fallback]
 * @returns {'zh'|'en'|'de'}
 */
function normalizeLang(raw, fallback = 'zh') {
    return resolveExplicitLang(raw) || fallback;
}

