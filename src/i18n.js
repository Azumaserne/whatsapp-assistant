/**
 * Translate a key in the given language with `{var}` interpolation.
 * @param {'zh'|'en'|'de'|string} lang
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 * @returns {string}
 */
function t(lang, key, vars = {}) {
    const code = normalizeLang(lang, 'zh');
    const dict = MESSAGES[code] || MESSAGES.zh;
    const template = dict[key] !== undefined ? dict[key] : (MESSAGES.zh[key] !== undefined ? MESSAGES.zh[key] : key);
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) => (
        vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : `{${k}}`
    ));
}

